const messages: Record<Locale, Record<VisitKey, string>> = { en, "zh-Hans": zhHans };

export function vt(locale: Locale, key: VisitKey, vars?: Record<string, string | number>): string {
  const template = messages[locale][key] ?? messages.en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole,
  );
}

/** "24 Aug" / "8月24日" from YYYY-MM-DD. */
export function shortDate(iso: string, locale: Locale): string {
  const [, m, d] = iso.split("-").map(Number);
  if (locale === "zh-Hans") return `${m}月${d}日`;
  const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  return `${d} ${MONTHS[m - 1]}`;
}
