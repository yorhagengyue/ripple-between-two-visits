const TABLE: Record<MedsLocale, Record<MedsAccountKey, string>> = { "zh-Hans": zh, en };

export function mx(locale: MedsLocale, key: MedsAccountKey, vars: Record<string, string | number> = {}): string {
  let s = TABLE[locale][key] ?? TABLE["zh-Hans"][key];
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function slotWords(locale: MedsLocale, slots: readonly string[]): string {
  const words = slots.map((s) => mx(locale, `slot.${s as DaySlot}` as MedsAccountKey));
  return locale === "en" ? words.join(", ") : words.join("、");
}

export function statusWords(locale: MedsLocale, status: MedStatus): string {
  return mx(locale, `status.${status}` as MedsAccountKey);
}

export function patientStatusWords(locale: MedsLocale, s: PatientMedStatus): string {
  return mx(locale, `patient.${s}` as MedsAccountKey);
}

export function fieldWords(locale: MedsLocale, f: ConfirmField): string {
  return mx(locale, `field.${f}` as MedsAccountKey);
}

