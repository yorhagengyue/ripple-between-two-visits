const messages: Record<Locale, Record<HerKey, string | string[]>> = { "zh-Hans": zh, en };

/**
 * One of her sentences, its names filled in. `{dad}` and the words for him ({he}, {his}, {him}, {He}, {His},
 * {himself}) come from `vars.dad`, her word for him (lib/care/copy.ts elderWords: 「妈妈」 gives 她, a name stands for
 * itself); a sentence asked for without it says 爸爸 / 他.
 */
export function hc(locale: Locale, key: HerKey, vars: Record<string, string | number> = {}): string {
  const raw = messages[locale]?.[key] ?? zh[key];
  const t = Array.isArray(raw) ? raw.join(" ") : raw;
  return fillHer(t, locale, vars);
}

export function hcList(locale: Locale, key: HerKey, vars: Record<string, string | number> = {}): string[] {
  const raw = messages[locale]?.[key] ?? zh[key];
  return (Array.isArray(raw) ? raw : [raw]).map((t) => fillHer(t, locale, vars));
}
