const messages: Record<Locale, Record<HisKey, string>> = { "zh-Hans": zh, en };

export function pc(locale: Locale, key: HisKey, vars: Record<string, string | number> = {}): string {
  const t = messages[locale]?.[key] ?? zh[key];
  return t.replace(/\{(\w+)\}/g, (whole, name: string) => (Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole));
}
